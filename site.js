// Awsome-Fable5.2-Game — waterfall front-end (bilingual zh / en).
// Data source: data/cases.json (single source of truth).
// English content uses title_en / summary_en when present, else falls back
// to the original fields. Layout: JS-managed flex columns — expanding a
// card's prompt only grows that card's own column (no global reflow).
(function () {
  var STR = {
    zh: {
      sub: 'AI 生成网页游戏案例索引 — 点开即玩 · 分类 · 提示词原文',
      notice: '收录社区里用 AI 一句话生成的可玩网页游戏：每个案例都附可验证的在线试玩链接与提示词原文；模型归属以原作者标注为准，致敬作品与原厂无关，版权归各原作者所有。',
      repo: 'GitHub 仓库',
      submit: '📥 提交游戏',
      pills: {
        all: '全部',
        racing: '🏎️ 竞速',
        shooter: '🔫 射击',
        casual: '🚲 休闲',
        moba: '⚔️ MOBA 对战',
        action: '🥷 动作'
      },
      searchPh: '搜索标题 / 作者 / 技术栈…',
      count: function (total, shown) {
        return '共 ' + total + ' 款游戏' + (shown !== total ? '（显示 ' + shown + ' 款）' : '');
      },
      viewPrompt: '查看 Prompt',
      source: '🔗 来源',
      play: '🕹️ 在线试玩',
      alt: '备用链接',
      loading: '加载案例中…',
      empty: '没有符合条件的游戏。',
      loadFail: function (m) { return '案例数据加载失败（' + m + '），请到 GitHub 仓库查看。'; },
      footer: '索引与整理以 MIT 发布；游戏内容与版权归各原作者所有。数据来自 <a href="https://github.com/zqingdut/Awsome-Fable5.2-Game/blob/main/data/cases.json" target="_blank" rel="noopener">data/cases.json</a>。',
      promptFallback: '未公开'
    },
    en: {
      sub: 'An index of AI-generated playable web games — play instantly · by genre · verbatim prompts',
      notice: 'Community web games generated by AI from a single prompt. Every case links to a verified playable build with its verbatim prompt; model attribution follows the original authors. Fan tributes are not affiliated with the original titles. All content belongs to its authors.',
      repo: 'GitHub Repo',
      submit: '📥 Submit a Game',
      pills: {
        all: 'All',
        racing: '🏎️ Racing',
        shooter: '🔫 Shooter',
        casual: '🚲 Casual',
        moba: '⚔️ MOBA',
        action: '🥷 Action'
      },
      searchPh: 'Search titles / authors / stack…',
      count: function (total, shown) {
        return total + ' games' + (shown !== total ? ' (' + shown + ' shown)' : '');
      },
      viewPrompt: 'View Prompt',
      source: '🔗 Source',
      play: '🕹️ Play Now',
      alt: 'Mirror',
      loading: 'Loading games…',
      empty: 'No games match.',
      loadFail: function (m) { return 'Failed to load case data (' + m + '). Please check the GitHub repo.'; },
      footer: 'The index is MIT-licensed; games belong to their original authors. Data from <a href="https://github.com/zqingdut/Awsome-Fable5.2-Game/blob/main/data/cases.json" target="_blank" rel="noopener">data/cases.json</a>.',
      promptFallback: 'Not published'
    }
  };

  var grid = document.getElementById('grid');
  var countEl = document.getElementById('count');
  var searchEl = document.getElementById('search');
  var activeCat = 'all';
  var allCases = [];
  var lastColCount = 0;

  var lang = 'zh';
  try {
    var param = new URLSearchParams(window.location.search).get('lang');
    var saved = window.localStorage.getItem('f52g-lang');
    if (param === 'en' || param === 'zh') lang = param;
    else if (saved === 'en' || saved === 'zh') lang = saved;
  } catch (e) { /* keep default */ }

  function S() { return STR[lang]; }

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function colCount() {
    var w = grid.clientWidth || window.innerWidth;
    if (w >= 1000) return 3;
    if (w >= 640) return 2;
    return 1;
  }

  function pick(item, enField, field) {
    if (lang === 'en' && item[enField]) return item[enField];
    return item[field];
  }

  function cardHTML(item) {
    var s = S();
    var title = pick(item, 'title_en', 'title');
    var summary = pick(item, 'summary_en', 'summary');
    var metaBits = [esc(item.author), esc(item.created_at)];
    if (item.model) metaBits.push(esc(item.model));

    var chips = (item.tech_stack || [])
      .map(function (t) { return '<span class="chip">' + esc(t) + '</span>'; })
      .join('');

    var play = item.play_url
      ? '<a href="' + esc(item.play_url) + '" target="_blank" rel="noopener">' + s.play + '</a>'
      : '';
    var source = item.source_url
      ? '<a href="' + esc(item.source_url) + '" target="_blank" rel="noopener">' + s.source + '</a>'
      : '';
    var alts = (item.alt_urls || [])
      .map(function (u, i) {
        return '<a href="' + esc(u) + '" target="_blank" rel="noopener">' + s.alt + (item.alt_urls.length > 1 ? ' ' + (i + 1) : '') + '</a>';
      })
      .join('');

    return (
      '<article class="card">' +
      (item.preview_webp
        ? '<img class="preview" loading="lazy" src="' + esc(item.preview_webp) + '" alt="' + esc(title) + '" />'
        : '') +
      '<div class="body">' +
      '<h3>' + esc(title) +
      (item.verification ? '<span class="badge">' + esc(item.verification) + '</span>' : '') +
      '</h3>' +
      '<div class="meta">' + metaBits.join(' · ') + '</div>' +
      '<p class="summary">' + esc(summary) + '</p>' +
      (chips ? '<div class="chips">' + chips + '</div>' : '') +
      '<button class="prompt-toggle" type="button" aria-expanded="false">' +
      '<span class="arrow">▸</span>' + s.viewPrompt + '</button>' +
      '<div class="prompt-wrap"><div class="prompt-inner"><pre>' +
      esc(item.prompt || s.promptFallback) +
      '</pre></div></div>' +
      '<div class="links">' + play + source + alts + '</div>' +
      '</div></article>'
    );
  }

  function render() {
    var s = S();
    var q = (searchEl.value || '').trim().toLowerCase();
    var rows = allCases.filter(function (c) {
      if (activeCat !== 'all' && c.category !== activeCat) return false;
      if (!q) return true;
      var hay = [c.title, c.title_en, c.author, c.summary, c.summary_en, (c.tech_stack || []).join(' ')]
        .join(' ')
        .toLowerCase();
      return hay.indexOf(q) >= 0;
    });

    countEl.textContent = s.count(allCases.length, rows.length);

    if (!rows.length) {
      grid.innerHTML = '<p class="empty">' + s.empty + '</p>';
      lastColCount = 0;
      return;
    }

    var n = colCount();
    lastColCount = n;
    grid.innerHTML = '';
    var cols = [];
    for (var i = 0; i < n; i++) {
      var col = document.createElement('div');
      col.className = 'col';
      grid.appendChild(col);
      cols.push(col);
    }
    rows.forEach(function (item) {
      var target = cols[0];
      for (var j = 1; j < cols.length; j++) {
        if (cols[j].offsetHeight < target.offsetHeight) target = cols[j];
      }
      var t = document.createElement('template');
      t.innerHTML = cardHTML(item).trim();
      target.appendChild(t.content.firstElementChild);
    });
  }

  function applyStatic() {
    var s = S();
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
    document.getElementById('heroSub').textContent = s.sub;
    document.getElementById('heroNotice').textContent = s.notice;
    document.getElementById('btnRepo').textContent = s.repo;
    document.getElementById('btnSubmit').textContent = s.submit;
    document.getElementById('footerText').innerHTML = s.footer;
    searchEl.placeholder = s.searchPh;
    document.querySelectorAll('.pill').forEach(function (p) {
      var cat = p.getAttribute('data-cat');
      if (s.pills[cat]) p.textContent = s.pills[cat];
    });
    document.getElementById('langZh').classList.toggle('active', lang === 'zh');
    document.getElementById('langEn').classList.toggle('active', lang === 'en');
    var lt = document.getElementById('loadingText');
    if (lt) lt.textContent = s.loading;
  }

  function setLang(next) {
    if (next !== 'zh' && next !== 'en') return;
    lang = next;
    try { window.localStorage.setItem('f52g-lang', lang); } catch (e) { /* ignore */ }
    applyStatic();
    render();
  }

  document.getElementById('langZh').addEventListener('click', function () { setLang('zh'); });
  document.getElementById('langEn').addEventListener('click', function () { setLang('en'); });

  grid.addEventListener('click', function (e) {
    var btn = e.target.closest('.prompt-toggle');
    if (!btn) return;
    var wrap = btn.parentElement.querySelector('.prompt-wrap');
    var open = wrap.classList.toggle('open');
    btn.setAttribute('aria-expanded', open ? 'true' : 'false');
  });

  document.getElementById('filters').addEventListener('click', function (e) {
    var btn = e.target.closest('.pill');
    if (!btn) return;
    document.querySelectorAll('.pill').forEach(function (p) { p.classList.remove('active'); });
    btn.classList.add('active');
    activeCat = btn.getAttribute('data-cat');
    render();
  });
  searchEl.addEventListener('input', render);

  var resizeTimer = null;
  window.addEventListener('resize', function () {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(function () {
      if (allCases.length && colCount() !== lastColCount) render();
    }, 150);
  });

  applyStatic();

  fetch('data/cases.json')
    .then(function (r) {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return r.json();
    })
    .then(function (data) {
      allCases = Array.isArray(data) ? data : [];
      render();
    })
    .catch(function (err) {
      grid.innerHTML = '<p class="empty">' + esc(S().loadFail(err.message)) + '</p>';
    });
})();
